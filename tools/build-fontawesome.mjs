#!/usr/bin/env node
/**
 * build-fontawesome.mjs
 *
 * Rebuilds the Font Awesome subset used by the site:
 *   1. Scans all site source (PHP/JS) for `fa-*` icon class names.
 *   2. Extracts the matching icon rules + base rules from assets/vendor/fa-all.css.
 *   3. Writes assets/css/fontawesome.min.css
 *   4. Subsets assets/vendor/webfonts/*.woff2 to the used codepoints via pyftsubset
 *      and writes assets/fonts/fa-solid-900.woff2 / fa-regular-400.woff2
 *
 * Requires: node, python with fonttools + brotli (pyftsubset on PATH).
 * Run from the repo root: node tools/build-fontawesome.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKIP_DIRS = new Set(['.git', 'node_modules', 'assets', 'tools']);
const SKIP_FILES = new Set(['router.php']);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (!SKIP_DIRS.has(entry)) walk(full, out);
    } else if (/\.(php|js)$/i.test(entry) && !SKIP_FILES.has(entry)) {
      out.push(full);
    }
  }
  return out;
}

// 1. collect used icon names
const used = new Map(); // name -> [files]
for (const file of walk(root)) {
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(/\bfa-([a-z0-9][a-z0-9-]*)/g)) {
    const name = m[1];
    if (!used.has(name)) used.set(name, []);
    const rel = relative(root, file);
    if (!used.get(name).includes(rel) && used.get(name).length < 4) used.get(name).push(rel);
  }
}

// 2. parse fa-all.css
const faCss = readFileSync(join(root, 'assets/vendor/fa-all.css'), 'utf8');
const iconMap = new Map(); // icon name -> codepoint hex
for (const m of faCss.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const selectors = m[1].split(',').map((s) => s.trim());
  const body = m[2].replace(/\s+/g, ' ').trim();
  const content = body.match(/^content: "\\([0-9a-f]{2,6})";$/i);
  if (!content) continue;
  const allIconSelectors = selectors.every((s) => /^\.fa-[a-z0-9-]+(?:::?before)$/.test(s));
  if (!allIconSelectors) continue;
  for (const s of selectors) {
    const name = s.replace(/^\.fa-/, '').replace(/(:::?)before$/, '');
    if (!iconMap.has(name)) iconMap.set(name, content[1].toLowerCase());
  }
}

const matched = new Map();
const unmatched = [];
for (const [name, files] of used) {
  if (iconMap.has(name)) matched.set(name, iconMap.get(name));
  else unmatched.push({ name, files });
}

// 3. write CSS
const iconRules = [...matched.entries()]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([name, cp]) => `.fa-${name}::before{content:"\\${cp}"}`)
  .join('\n');

const css = `/*! Font Awesome Free 6.4.0 subset - generated by tools/build-fontawesome.mjs - see fa-all.css for license */
.fa{font-family:var(--fa-style-family,"Font Awesome 6 Free");font-weight:var(--fa-style,900)}
.fa,.fas,.fa-solid,.far,.fa-regular{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}
.fas,.fa-solid,.far,.fa-regular{font-family:'Font Awesome 6 Free'}
.fas,.fa-solid{font-weight:900}
.far,.fa-regular{font-weight:400}
@font-face{font-family:'Font Awesome 6 Free';font-style:normal;font-weight:900;font-display:block;src:url('../fonts/fa-solid-900.woff2') format('woff2')}
@font-face{font-family:'Font Awesome 6 Free';font-style:normal;font-weight:400;font-display:block;src:url('../fonts/fa-regular-400.woff2') format('woff2')}
${iconRules}
`;
writeFileSync(join(root, 'assets/css/fontawesome.min.css'), css);

// 4. subset fonts
const unicodes = 'U+' + [...new Set([...matched.values()])].join(',U+');
for (const [src, out] of [
  ['fa-solid-900.ttf', 'fa-solid-900.woff2'],
  ['fa-regular-400.ttf', 'fa-regular-400.woff2'],
]) {
  execFileSync('pyftsubset', [
    join(root, 'assets/vendor/webfonts', src),
    `--unicodes=${unicodes}`,
    '--flavor=woff2',
    `--output-file=${join(root, 'assets/fonts', out)}`,
  ], { stdio: 'inherit' });
}

console.log(`used icons: ${used.size}, matched: ${matched.size}, css bytes: ${css.length}`);
if (unmatched.length) {
  console.log('NOT FOUND in fa-all.css (rendered as nothing before AND after - verify):');
  for (const u of unmatched) console.log(`  fa-${u.name} (${u.files.join(', ')})`);
}
