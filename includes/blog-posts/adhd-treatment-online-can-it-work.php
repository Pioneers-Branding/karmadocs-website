<h2 id="can-online-adhd-treatment-work"><span style="font-weight: 400;">Can Online ADHD Treatment Work?</span></h2>
<strong>Yes!</strong><span style="font-weight: 400;"> According to the American Psychiatry Association, remote mental health care is </span><em><span style="font-weight: 400;">just as effective</span></em><span style="font-weight: 400;"> as in-person care.</span><span style="font-weight: 400;"> </span>

&nbsp;

<strong>Here’s the latest research and recommendations for digital ADHD treatment: </strong>

&nbsp;
<ul>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">In a meta-analysis, online ADHD treatments were </span><em><span style="font-weight: 400;">more effective</span></em><span style="font-weight: 400;"> than making patients wait for in-person care.</span><span style="font-weight: 400;"> Waiting lists are standard practices for offices that are full. Yet they can mean that patients put off getting help. </span><strong>If you’re on a waiting list to see a psychiatrist in person, you’re better off scheduling a remote visit instead. </strong></li>
</ul>
&nbsp;
<ul>
 	<li style="font-weight: 400;" aria-level="1"><strong>Experts recommend keeping treatment for ADHD simple so it’s easier to follow the plan.</strong><span style="font-weight: 400;"> Remote visits help simplify therapy, and patients find it easier to attend sessions via a phone or tablet. Email reminders, phone alerts, and physical appointment schedules can also make it easier to keep up with treatment.</span><span style="font-weight: 400;"> </span></li>
</ul>
