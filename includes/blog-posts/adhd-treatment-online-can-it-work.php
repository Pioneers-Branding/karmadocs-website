<h2 id="symptoms-of-adhd"><span style="font-weight: 400;">Symptoms of ADHD</span></h2>
<span style="font-weight: 400;">Everyone experiences ADHD differently. But here are the common symptoms we look for: </span>

&nbsp;
<ul>
 	<li style="font-weight: 400;" aria-level="1"><strong>Problems with attention</strong><span style="font-weight: 400;">. This might look like low performance at work or low grades in school. </span></li>
</ul>
&nbsp;
<ul>
 	<li aria-level="1"><strong>Trouble concentrating. </strong><span style="font-weight: 400;">Not being able to read a full chapter of a book or losing track of a conversation may be signs of poor concentration. </span></li>
</ul>
&nbsp;
<ul>
 	<li aria-level="1"><strong>Being disorganized. </strong><span style="font-weight: 400;">This can lead to missing events on accident, or losing track of work projects. </span></li>
</ul>
&nbsp;
<ul>
 	<li aria-level="1"><strong>Losing things (</strong><span style="font-weight: 400;">like your keys wallet, or phone) several times a day.</span></li>
</ul>
&nbsp;
<ul>
 	<li aria-level="1"><strong>Forgetting tasks, conversations, or ideas. </strong><span style="font-weight: 400;">For example, a friend might talk about a movie you saw together last week, but you might not remember it as well as they do. </span></li>
</ul>
&nbsp;
<ul>
 	<li aria-level="1"><strong>Impulsiveness </strong><span style="font-weight: 400;">that impacts your daily life. Quitting your job spontaneously or booking an expensive vacation may be signs of impulsivity. </span></li>
</ul>
&nbsp;

<span style="font-weight: 400;">Do any of these symptoms sound familiar to you? The thing about ADHD is that people without it experience these symptoms too. We’ve all had moments of forgetfulness or times when we made a decision on an impulse. </span><strong>The difference with ADHD is that these behaviors become patterns that make life a lot harder. </strong>

&nbsp;

<span style="font-weight: 400;">Keeping a job is much more difficult if you’re forgetting about projects and meetings. Making good grades is nearly impossible if you can’t concentrate during lectures. Forgetting things here and there and losing focus is normal. </span><strong>But</strong> <strong>if these problems are chronic, they could be a sign of ADHD. </strong>

&nbsp;

