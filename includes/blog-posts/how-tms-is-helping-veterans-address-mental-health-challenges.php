<p class="wp-block-paragraph">TMS helps veterans recapture the motivation to take action to overcome feelings of hopelessness.</p>

<p class="wp-block-paragraph">2. Decreased PTSD Triggers:</p>

<p class="wp-block-paragraph">TMS reduces sensitivity to trauma-related cues, making it easier to get through the tasks in day-to-day living.</p>

<p class="wp-block-paragraph">3. Improved Sleep Quality:</p>

<p class="wp-block-paragraph">Many veterans report sleeping better and more deeply in the days after TMS.</p>

<p class="wp-block-paragraph">4. Improved Emotional Regulation:</p>

<p class="wp-block-paragraph">Easier control of emotions can limit angry outbursts and irritability.</p>

<p class="wp-block-paragraph">5. Reduced Anxiety Levels:</p>

<p class="wp-block-paragraph">Magnetic stimulation reduces overactive brain circuits related to anxiety.</p>

<p class="wp-block-paragraph">6. Increase Cognitive Function:</p>

<p class="wp-block-paragraph">With repeated sessions, focusing, memory, and decision-making increase.</p>

<p class="wp-block-paragraph">7. New Hope for Treatment-Resistant Depression:</p>

<p class="wp-block-paragraph">For veterans with treatment-resistant depression, TMS represents a new avenue for treatment.</p>

<p class="wp-block-paragraph">8. Long-lasting Effects:<br />The benefits of TMS last months to years, especially if maintenance sessions are obtained.</p>

<p class="wp-block-paragraph">9. Increased Propensity to Engage in Daily Life:</p>

<p class="wp-block-paragraph">Increased levels of functioning yield greater productivity at work with better family relationships, more engagement in leisure activities, and improved overall quality of life.</p>

<p class="wp-block-paragraph">10. Low Incidence of Side Effects:</p>

<p class="wp-block-paragraph">Except for very mild discomfort to the scalp during stimulation for most patients, TMS has very low overall side effects.</p>

<p class="wp-block-paragraph">11. Increased Resilience:</p>

<p class="wp-block-paragraph">Veterans often describe feeling more resilient in dealing with stressors.</p>

<p class="wp-block-paragraph">12. Social Reintegration:</p>

