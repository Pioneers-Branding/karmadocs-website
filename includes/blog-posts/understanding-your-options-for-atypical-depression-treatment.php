<span style="font-weight: 400;">Depression is different for everyone. Maybe you’ve looked up the symptoms of depression and felt like they didn&#8217;t represent your situation. Maybe you’ve tried medications and therapy without relief. To give you more information about depression variations and their options, we’re getting into </span><b>what atypical depression is and your treatment options. </b>
<h2 id="what-is-atypical-depression"><span style="font-weight: 400;">What Is Atypical Depression? </span></h2>
<span style="font-weight: 400;">“Atypical” doesn’t mean that this form of depression is strange or unusual. It just means that </span><b>you may experience the symptoms you normally associate with depression, along with a few others.</b><span style="font-weight: 400;"> Here are some additional symptoms someone with atypical depression may experience:</span>

&nbsp;
<ul>
 	<li style="font-weight: 400;" aria-level="1"><b>Temporary mood improvements</b><span style="font-weight: 400;">, which may be mistaken for permanent changes in the moment. It’s sometimes called </span><b>mood reactivity.</b><span style="font-weight: 400;"> This is usually in response to real or potential positive life events. </span></li>
</ul>
&nbsp;

<span style="font-weight: 400;">Because these fluctuations in mood happen in addition to regular depression symptoms, atypical depression is sometimes called </span><b>major depression with atypical features.</b><span style="font-weight: 400;"> In addition to mood reactivity, having two or more of the following symptoms may mean your depression is atypical:</span>

&nbsp;
<ul>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Appetite increases and weight changes</span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Sleeping excessively</span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Feeling heavy in your legs and arms </span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Feeling very sensitive to criticism or rejection, which leads to problems in your social life and at work  </span></li>
</ul>
&nbsp;

<span style="font-weight: 400;">These added symptoms define atypical depression. But let’s break down the key differences between atypical and Major Depressive Disorder. </span>
