<i><span style="font-weight: 400;">You’ve probably heard of depression before, but you might not have heard of </span></i><b><i>atypical depression.</i></b><i><span style="font-weight: 400;"> This sub-variant leads to more inconsistent mood symptoms, which can make people think that they don’t have depression at all. And it tends to afflict people with another psychiatric diagnosis, like bipolar disorder or cyclothymia. Let’s dig into </span></i><b><i>what atypical depression is and your treatment options. </i></b>

&nbsp;

<span style="font-weight: 400;">Depression is a mood disorder that makes you lose interest in the things you used to enjoy. But it comes in many forms and looks and feels different for different people. The Diagnostic and Statistical Manual lists </span><b>five main variations,</b><span style="font-weight: 400;"> which are:</span>

&nbsp;
<ul>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Disruptive Mood Dysregulation Disorder</span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Major Depressive Disorder (MDD)</span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Persistent Depressive Disorder (or dysthymia)</span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Premenstrual Dysphoric Disorder</span></li>
 	<li style="font-weight: 400;" aria-level="1"><span style="font-weight: 400;">Depressive Disorder Related to a Medical Condition</span></li>
</ul>
&nbsp;

<span style="font-weight: 400;">Each of these mood disorders share similar symptoms. </span><b>People with all forms of depression share sadness, irritability, and somatic or cognitive changes. </b><span style="font-weight: 400;">Yet their treatment options may be different because of the root cause of their symptoms. </span>

&nbsp;

<span style="font-weight: 400;">Atypical depression is categorized under Major Depressive Disorder, yet there are some specific symptoms that make it distinct from others on the list. Between 15% and 36% of depressed people are thought to have atypical depression.</span><span style="font-weight: 400;"> And its differences mean that you may get different treatments recommended. </span>

&nbsp;

