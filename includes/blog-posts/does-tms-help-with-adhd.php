<h2 class="wp-block-heading" id="treating-comorbid-adhd-and-depression">The Comorbidity Factor: Addressing Co-Occurring Depression</h2>

<p class="wp-block-paragraph">In adult psychiatry, ADHD rarely appears alone. Over <strong>60% of adults with ADHD meet diagnostic criteria for co-occurring mood disorders</strong>, primarily <a href="/depression">Major Depressive Disorder (MDD)</a> or generalized <a href="/anxiety">anxiety disorders</a>.</p>

<p class="wp-block-paragraph">This co-occurrence creates a painful cycle: chronic executive dysfunction produces setbacks, fueling depression. In turn, depressive fatigue worsens processing speed. Furthermore, stimulants often exacerbate baseline anxiety, causing panic or insomnia.</p>

<h3 class="wp-block-heading">Why TMS Offers Dual Relief:</h3>

<ul class="wp-block-list">
<li><strong>FDA-Cleared Depression Coverage:</strong> Because TMS is FDA-cleared and covered by Medicare and major insurers for depression, patients with comorbid ADHD frequently qualify for full insurance reimbursement.</li>
<li><strong>Shared Neural Targets:</strong> The left prefrontal cortex targeted for depression is intimately connected to executive motivation. As depressive fog lifts, working memory and task initiation naturally improve.</li>
<li><strong>Calming Limbic Reactivity:</strong> TMS reinforces frontal control over the emotional amygdala without triggering stimulant agitation.</li>
</ul>

