<h3 class="wp-block-heading">1. Box Breathing (Works in Minutes)</h3>

<p class="wp-block-paragraph">Box breathing is a simple but powerful technique used by Navy SEALs and therapists alike to <strong>reduce anxiety quickly</strong>. Here&#8217;s how to do it:</p>

<ul class="wp-block-list">
<li>Inhale slowly for 4 counts</li>

<li>Hold your breath for 4 counts</li>

<li>Exhale slowly for 4 counts</li>

<li>Hold for 4 counts before the next inhale</li>

<li>Repeat 4–5 times</li>
</ul>

