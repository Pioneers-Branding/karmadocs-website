<p class="wp-block-paragraph">Writing down your anxious thoughts can help you see them more objectively. Try writing three things you are worried about, followed by three pieces of evidence that contradict each worry. This cognitive technique is a cornerstone of CBT (Cognitive Behavioral Therapy).</p>

