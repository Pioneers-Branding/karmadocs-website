<h3 class="wp-block-heading">3. Progressive Muscle Relaxation</h3>

<p class="wp-block-paragraph">Anxiety lives in the body. By intentionally tensing and releasing muscle groups — starting from your feet and moving up to your face — you can release physical tension and signal to your nervous system that it is safe to relax.</p>

<h3 class="wp-block-heading">4. Limit Caffeine and Sugar</h3>

<p class="wp-block-paragraph">Both caffeine and sugar can trigger or worsen anxiety symptoms by increasing your heart rate and blood sugar fluctuations. Try switching to herbal tea and notice if your baseline anxiety decreases over a few days.</p>

<h3 class="wp-block-heading">5. Move Your Body</h3>

<p class="wp-block-paragraph">Exercise is one of the most effective natural remedies for anxiety. Even a 20-minute brisk walk releases endorphins and lowers cortisol (the stress hormone). Aim for at least 30 minutes of moderate exercise most days of the week.</p>

