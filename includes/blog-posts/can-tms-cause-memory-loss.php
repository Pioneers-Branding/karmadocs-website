<div class="wp-block-group faq-accordion-section" style="margin-top:24px;margin-bottom:32px;">

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">1. Can TMS therapy cause short-term or long-term memory loss?</h3>
<p class="wp-block-paragraph">No. Clinical studies and FDA trials confirm that TMS therapy does not cause short-term or long-term memory loss. TMS targets mood centers without affecting memory structures like the hippocampus.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">2. Why do people confuse TMS with ECT memory loss?</h3>
<p class="wp-block-paragraph">Both are interventional treatments, leading to confusion. However, ECT induces brain seizures under anesthesia—causing memory risks—while TMS uses gentle, focal magnetic pulses with no seizures and zero memory loss.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">3. Can depression itself cause memory problems before starting TMS?</h3>
<p class="wp-block-paragraph">Yes. Major depression causes cognitive brain fog, forgetfulness, and poor focus. As depression improves during TMS, these cognitive difficulties typically resolve.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">4. Does TMS therapy improve cognitive function and focus?</h3>
<p class="wp-block-paragraph">Yes. Research demonstrates that resolving depression with TMS enhances working memory, attention, and executive function by restoring brain connectivity.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">5. What are the most common side effects of TMS therapy?</h3>
<p class="wp-block-paragraph">Common side effects include mild scalp tapping sensations, minor post-session headaches, and mild fatigue. All are temporary and resolve without affecting memory.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">6. Does TMS therapy cause permanent brain damage?</h3>
<p class="wp-block-paragraph">No. TMS therapy is safe and FDA-approved. It does not cause brain damage or cell loss. Instead, it promotes healthy neuroplasticity and neural growth.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">7. Can I drive home by myself after a TMS session?</h3>
<p class="wp-block-paragraph">Yes. TMS requires no sedation and does not affect mental alertness, allowing patients to drive safely immediately after sessions.</p>

