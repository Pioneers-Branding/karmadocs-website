<h2 class="wp-block-heading" id="when-to-see-a-psychiatrist">When Should You See a Psychiatrist for Anxiety?</h2>

<p class="wp-block-paragraph"><strong>See a psychiatrist if anxiety has lasted more than two to four weeks, self-help strategies aren&#8217;t enough, or symptoms are disrupting work, school, sleep, or relationships.</strong> Seek help sooner if you notice:</p>

<ul class="wp-block-list">
<li>Recurring panic attacks or fear of having another one</li>
<li>Avoiding work, driving, or leaving home</li>
<li>Using alcohol or substances to cope</li>
<li>Symptoms of depression such as hopelessness or loss of interest</li>
<li>Thoughts of self-harm. <strong>If you are in crisis, call or text 988</strong> (Suicide &amp; Crisis Lifeline) or 911 right away.</li>
</ul>

<p class="wp-block-paragraph">A psychiatrist can make an accurate diagnosis, rule out medical causes, and build a treatment plan that may include medication and therapy. Read <a href="/understanding-your-mental-health-the-vital-role-of-psychiatrists">the vital role of psychiatrists in mental health</a> to understand what to expect.</p>

