<h2 class="wp-block-heading" id="what-to-expect-during-deep-tms-treatment"><strong>What to Expect During Deep TMS Treatment</strong></h2>

<p class="wp-block-paragraph">Deep TMS sessions are designed to be straightforward and well-tolerated.</p>

<ul class="wp-block-list">
<li>Sessions typically last 20–40 minutes<strong><br></strong></li>

<li>Patients remain awake and alert<br></li>

<li>No anesthesia or sedation is required<br></li>

<li>There is no recovery or downtime afterward</li>
</ul>

<p class="wp-block-paragraph">Most treatment plans involve multiple sessions over several weeks for optimal results.</p>

<h2 class="wp-block-heading" id="safety-and-tolerability-of-deep-tms"><strong>Safety and Tolerability of Deep TMS</strong></h2>

<p class="wp-block-paragraph">Deep TMS is considered safe and well-tolerated when administered according to established guidelines.</p>

<p class="wp-block-paragraph">Possible side effects are similar to standard TMS and may include:</p>

<ul class="wp-block-list">
<li>Mild scalp discomfort<br></li>

<li>Temporary headaches<br></li>

<li>Facial muscle twitching during sessions</li>
</ul>

<p class="wp-block-paragraph">Serious side effects are rare and minimized through proper screening and monitoring.</p>

