<h2 class="wp-block-heading" id="frequently-asked-questions">Frequently Asked Questions (FAQs)</h2>

<div class="wp-block-group faq-accordion-section" style="margin-top:24px;margin-bottom:32px;">

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">1. Is TMS therapy a hoax or just a placebo effect?</h3>
<p class="wp-block-paragraph">No. Double-blind sham-controlled clinical trials prove that active TMS produces significantly higher response and remission rates than inert sham coils. Functional brain imaging confirms physical increases in prefrontal neural activity and blood flow after active TMS.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">2. Is TMS therapy approved by the FDA?</h3>
<p class="wp-block-paragraph">Yes. The FDA first cleared repetitive TMS for treatment-resistant Major Depressive Disorder in 2008, with later clearances for OCD, migraine prevention, and smoking cessation backed by randomized clinical trials.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">3. Why do some patients claim TMS didn\'t work for them?</h3>
<p class="wp-block-paragraph">TMS has a 50% to 60% response rate, meaning roughly 40% of patients do not experience substantial relief. Depression has diverse neurobiological origins, and no medical treatment works for every individual. Non-response reflects biological complexity, not that the therapy is a scam.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">4. Does health insurance cover TMS if it\'s considered experimental?</h3>
<p class="wp-block-paragraph">TMS is not considered experimental. Medicare, Medicaid, and major commercial insurers (Aetna, Anthem Blue Cross, Blue Shield, Cigna, UnitedHealthcare, Tricare) cover TMS when clinical guidelines for treatment-resistant depression are met.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">5. How is clinical TMS different from at-home brain stimulation devices?</h3>
<p class="wp-block-paragraph">Clinical TMS utilizes high-intensity, focused magnetic pulses (1.5 to 3 Tesla) administered with medical-grade equipment under psychiatric supervision. Consumer headbands emit weak, unregulated electrical currents without clinical validation.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">6. Can TMS therapy cause memory loss or brain damage?</h3>
<p class="wp-block-paragraph">No. TMS does not cause brain damage, cognitive decline, or memory loss. Unlike Electroconvulsive Therapy (ECT), it does not induce seizures or require anesthesia. Memory and cognitive function often improve as depression lifts.</p>

<h3 class="wp-block-heading" style="color:#603177;font-size:1.2rem;font-weight:700;">7. How many sessions are required before TMS starts working?</h3>
<p class="wp-block-paragraph">A standard TMS protocol consists of 36 sessions delivered five days a week over six to nine weeks. Most patients begin noticing mood improvements between weeks three and four of continuous care.</p>

