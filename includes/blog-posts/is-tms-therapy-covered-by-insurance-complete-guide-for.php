<h2 class="wp-block-heading" id="criteria-for-insurance-coverage"><strong>Criteria for Insurance Coverage</strong></h2>

<p class="wp-block-paragraph">Most insurers require proof that the patient has not achieved adequate results from traditional treatments, especially when evaluating eligibility and the <strong><a href="/the-cost-of-tms-without-insurance-your-complete-guide">cost of TMS therapy without insurance</a></strong>.<br></p>

<p class="wp-block-paragraph"><strong>Common eligibility requirements include:</strong></p>

<ol class="wp-block-list">
<li><strong>Documented Diagnosis:</strong> Major Depressive Disorder or another approved condition.</li>

<li><strong>Medication History:</strong> Tried at least <strong>2–4 antidepressants</strong> without sufficient improvement.</li>

<li><strong>Psychotherapy Attempt:</strong> Completed a course of talk therapy or counseling.</li>

<li><strong>Age Requirement:</strong> Must be <strong>18 years or older</strong> (some exceptions for adolescents).</li>

<li><strong>TMS Prescription:</strong> Must be prescribed and administered by a qualified psychiatrist.</li>
</ol>

<p class="wp-block-paragraph">Once you meet these conditions, your insurance company will typically pre-approve TMS therapy.</p>

