<h2 class="wp-block-heading" id="cigna-tms-coverage-criteria">Cigna TMS Coverage Criteria &amp; Medical Necessity Guidelines</h2>

<p class="wp-block-paragraph">To qualify for Cigna TMS coverage for Major Depressive Disorder, a patient must meet established clinical benchmarks:</p>

<ol class="wp-block-list">
<li><strong>Adult Age:</strong> The patient must be 18 years of age or older.</li>
<li><strong>Confirmed MDD Diagnosis:</strong> Unipolar Major Depressive Disorder (single or recurrent), moderate to severe, verified by validated tools such as the PHQ-9, HAM-D, or BDI.</li>
<li><strong>Medication Resistance:</strong> Inadequate response or intolerance to <strong>at least two different antidepressant medications</strong> from separate classes (e.g., SSRIs, SNRIs, bupropion, TCAs), each taken at therapeutic dose for 4 to 6 weeks.</li>
<li><strong>Psychotherapy Trial:</strong> Evidence-based outpatient psychotherapy (such as CBT) without sufficient relief, or documented contraindication.</li>
<li><strong>No Active Psychosis:</strong> No active psychotic symptoms or acute crisis requiring inpatient hospitalization.</li>
<li><strong>Safety Clearance:</strong> No non-removable ferromagnetic metals in or near the head (e.g., aneurysm clips, cochlear implants) and no uncontrolled seizure disorders.</li>
<li><strong>Psychiatrist Supervision:</strong> Treatment must be prescribed and monitored by a board-certified psychiatrist.</li>
</ol>

